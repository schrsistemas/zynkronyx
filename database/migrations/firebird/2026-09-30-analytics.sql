      UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
      CONSTRAINT PK_ANALYTICS_INSIGHT PRIMARY KEY (ID),
      CONSTRAINT UQ_ANALYTICS_INSIGHT_TENANT_ID UNIQUE (TENANT_ID, ID),
